import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { DatabaseSync } from "node:sqlite";
import { gunzipSync } from "node:zlib";

const REPLICA_TABLES = [
  "version",
  "settings",
  "itemTypes",
  "itemTypesCombined",
  "fieldsCombined",
  "baseFieldMappingsCombined",
  "creatorTypes",
  "itemTypeCreatorTypes",
  "charsets",
  "libraries",
  "users",
  "groups",
  "items",
  "groupItems",
  "deletedItems",
  "itemDataValues",
  "itemData",
  "itemNotes",
  "itemAttachments",
  "itemAnnotations",
  "tags",
  "itemTags",
  "creators",
  "itemCreators",
  "relationPredicates",
  "itemRelations",
  "collections",
  "deletedCollections",
  "collectionItems",
] as const;

const packageRoot = resolve(import.meta.dirname, "..");
const pristinePath = join(
  packageRoot,
  "..",
  "scripts",
  "lib",
  "fixture",
  "pristine-zotero.sqlite.gz",
);
const outputFile = join(packageRoot, "src", "replica", "layout.generated.ts");

const sqlite = new DatabaseSync(":memory:");
sqlite.deserialize(gunzipSync(readFileSync(pristinePath)));

const rows = sqlite
  .prepare(
    "select type, name, tbl_name as tableName, sql from sqlite_schema where sql is not null and type in ('table', 'index') order by rowid",
  )
  .all() as { type: string; name: string; tableName: string; sql: string }[];
const kept = new Set<string>(REPLICA_TABLES);
const missing = REPLICA_TABLES.filter(
  (table) => !rows.some((row) => row.type === "table" && row.name === table),
);
if (missing.length > 0) {
  throw new Error(`the pristine database has no table ${missing.join(", ")}`);
}
const statements = rows
  .filter((row) => kept.has(row.tableName))
  .map((row) => row.sql);

const versions = Object.fromEntries(
  (
    sqlite
      .prepare(
        "select schema, version from version where schema in ('userdata', 'compatibility')",
      )
      .all() as { schema: string; version: number }[]
  ).map((row) => [row.schema, row.version]),
);

const charsets = (
  sqlite
    .prepare("select charsetID, charset from charsets order by charsetID")
    .all() as { charsetID: number; charset: string }[]
).map((row) => [row.charsetID, row.charset]);

writeFileSync(
  outputFile,
  [
    "// Generated by scripts/generate-replica-layout.ts - DO NOT EDIT.",
    "// Source: packages/scripts/lib/fixture/pristine-zotero.sqlite.gz",
    "",
    `export const REPLICA_TABLES = ${JSON.stringify(REPLICA_TABLES)} as const;`,
    "",
    `export const REPLICA_SCHEMA_VERSIONS = ${JSON.stringify({
      userdata: versions.userdata,
      compatibility: versions.compatibility,
    })} as const;`,
    "",
    `export const REPLICA_CHARSETS: readonly (readonly [number, string])[] = ${JSON.stringify(charsets)};`,
    "",
    `export const REPLICA_DDL: readonly string[] = ${JSON.stringify(statements)};`,
    "",
  ].join("\n"),
);
