import { readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";

import { dateFieldsOf } from "#date-fields.ts";

interface ZoteroSchema {
  readonly version: number;
  readonly itemTypes: readonly ZoteroSchemaItemType[];
  readonly meta: {
    readonly fields: Readonly<Record<string, { readonly type: string }>>;
  };
}

interface ZoteroSchemaItemType {
  readonly itemType: string;
  readonly fields: readonly { field: string; baseField?: string }[];
  readonly creatorTypes: readonly { creatorType: string; primary?: boolean }[];
}

const packageRoot = resolve(import.meta.dirname, "..");
const outputFile = join(packageRoot, "src", "vocabulary.ts");

const schema = JSON.parse(
  await readFile(join(packageRoot, "zotero-schema", "schema.json"), "utf8"),
) as ZoteroSchema;

await writeFile(outputFile, render(schema));

function render(schema: ZoteroSchema): string {
  const itemTypes = schema.itemTypes.map(
    ({ itemType, fields, creatorTypes }) => ({
      itemType,
      fields: fields.map(({ field, baseField }) =>
        baseField ? { field, baseField } : { field },
      ),
      creatorTypes: creatorTypes.map(({ creatorType, primary }) =>
        primary ? { creatorType, primary: true } : { creatorType },
      ),
    }),
  );
  const dateFields = dateFieldsOf(schema);
  return [
    "// Generated by scripts/generate-vocabulary.ts - DO NOT EDIT.",
    `// Schema version: ${schema.version}`,
    "",
    "export interface ZoteroVocabulary {",
    "  readonly version: number;",
    "  readonly itemTypes: readonly ZoteroVocabularyItemType[];",
    "  readonly dateFields: readonly string[];",
    "}",
    "",
    "export interface ZoteroVocabularyItemType {",
    "  readonly itemType: string;",
    "  readonly fields: readonly { readonly field: string; readonly baseField?: string }[];",
    "  readonly creatorTypes: readonly { readonly creatorType: string; readonly primary?: true }[];",
    "}",
    "",
    `export const ZOTERO_SCHEMA_VERSION = ${schema.version};`,
    "",
    `export const ZOTERO_VOCABULARY: ZoteroVocabulary = ${JSON.stringify({
      itemTypes,
      dateFields,
    }).replace("{", "{ version: ZOTERO_SCHEMA_VERSION, ")};`,
    "",
  ].join("\n");
}
