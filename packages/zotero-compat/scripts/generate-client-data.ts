import { regex } from "arkregex";
import { readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";

const packageRoot = resolve(import.meta.dirname, "..");
const clientRoot = join(packageRoot, "zotero-client");
const provenance = JSON.parse(
  await readFile(join(clientRoot, "provenance.json"), "utf8"),
) as { readonly commit: string };

await writeFile(
  join(packageRoot, "src", "isbn-ranges.ts"),
  renderIsbnRanges(
    await readFile(
      join(clientRoot, "chrome/content/zotero/xpcom/isbn.js"),
      "utf8",
    ),
  ),
);
await writeFile(
  join(packageRoot, "src", "date-formats.ts"),
  renderDateFormats(
    await readFile(
      join(clientRoot, "resource/schema/dateFormats.json"),
      "utf8",
    ),
    await readFile(join(clientRoot, "app/assets/multilocale.txt"), "utf8"),
    await readFile(join(clientRoot, "day-suffixes.json"), "utf8"),
  ),
);

type Ranges = Record<string, Record<string, string[]>>;

function renderIsbnRanges(source: string): string {
  const start = source.indexOf("var ranges = ");
  const end = source.indexOf("\n\t};", start);
  if (start === -1 || end === -1) {
    throw new Error("isbn.js has no ranges object");
  }
  const ranges = JSON.parse(
    source.slice(start + "var ranges = ".length, end + 3),
  ) as Ranges;
  const alias = regex(
    "^\\s*(?<targets>(?:ranges\\['97[89]'\\]\\['[0-9]+'\\] = )+)ranges\\['(?<prefix>97[89])'\\]\\['(?<group>[0-9]+)'\\];$",
    "gm",
  );
  const target = regex(
    "ranges\\['(?<prefix>97[89])'\\]\\['(?<group>[0-9]+)'\\] = ",
    "g",
  );
  let aliases = 0;
  let lines = 0;
  for (let line = alias.exec(source); line; line = alias.exec(source)) {
    lines += 1;
    const from = ranges[line.groups.prefix]?.[line.groups.group];
    if (from === undefined) {
      throw new Error(`isbn.js aliases an unknown group: ${line[0]}`);
    }
    target.lastIndex = 0;
    for (
      let found = target.exec(line.groups.targets);
      found;
      found = target.exec(line.groups.targets)
    ) {
      ranges[found.groups.prefix]![found.groups.group] = from;
      aliases += 1;
    }
  }
  const assignments = source.match(/^\s*ranges\[/gm)?.length ?? 0;
  if (assignments !== lines) {
    throw new Error(
      "isbn.js has an assignment that the generator does not read",
    );
  }
  if (aliases === 0) throw new Error("isbn.js has no group aliases");
  return [
    "// Generated by scripts/generate-client-data.ts - DO NOT EDIT.",
    `// Source: zotero/zotero ${provenance.commit} chrome/content/zotero/xpcom/isbn.js`,
    "",
    "export const ISBN_RANGES: Readonly<",
    "  Record<string, Readonly<Record<string, readonly string[]>>>",
    `> = ${JSON.stringify(ranges)};`,
    "",
  ].join("\n");
}

function renderDateFormats(
  source: string,
  shipped: string,
  suffixSource: string,
): string {
  const locales = shipped.trim().split(",");
  if (!locales.includes("en-US")) {
    throw new Error("multilocale.txt does not list en-US");
  }
  const formats = JSON.parse(source) as Record<
    string,
    { short: string[]; long: string[] }
  >;
  const daySuffixes = JSON.parse(suffixSource) as Record<string, string>;
  if (!Object.hasOwn(daySuffixes, "en-US")) {
    throw new Error("day-suffixes.json has no en-US entry");
  }
  return [
    "// Generated by scripts/generate-client-data.ts - DO NOT EDIT.",
    `// Source: zotero/zotero ${provenance.commit} resource/schema/dateFormats.json, app/assets/multilocale.txt, chrome/locale/*/zotero/zotero.properties (date.daySuffixes)`,
    "",
    `export const ZOTERO_LOCALES: readonly string[] = ${JSON.stringify(locales)};`,
    "",
    "export const DATE_FORMATS: Readonly<",
    "  Record<string, { readonly short: readonly string[]; readonly long: readonly string[] }>",
    `> = ${JSON.stringify(formats)};`,
    "",
    `export const DAY_SUFFIXES: Readonly<Record<string, string>> = ${JSON.stringify(daySuffixes)};`,
    "",
  ].join("\n");
}
