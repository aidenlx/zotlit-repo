import { cp, mkdir, readdir } from "node:fs/promises";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { defineConfig } from "vite";
import { analyzer, unstableRolldownAdapter } from "vite-bundle-analyzer";

import { obsidianI18n } from "@zotlit/obsidian-i18n/vite";
import { effectEntry, effectEntryCheck } from "@zotlit/plugin-kernel/vite";
import {
  EXCLUDE_MESSAGE_PREFIXES,
  INCLUDE_MESSAGES,
  TARGET_LOCALE_MESSAGE_PREFIXES,
} from "@zotlit/plugin-messages/language-pack-options";
import { getWorkspaceRoot } from "@zotlit/scripts/package-roots";
import { RUNTIMES } from "@zotlit/scripts/runtime-table";
import { obsidianBuildPlugin } from "@zotlit/scripts/shell/host-build";
import {
  BUNDLE_PACKAGE_DIR,
  PUBLISHED_PLUGINS,
} from "@zotlit/scripts/shell/plugins";

import {
  fullContractIRPath,
  pluginBuildBase,
  pluginCode,
} from "./scripts/build-base.ts";
import { chineseSegmenterGlue } from "./scripts/chinese-segmenter.ts";
import { embeddedWorker } from "./scripts/embedded-worker.ts";
import { nodeHttpModules } from "./scripts/node-http-modules.ts";
import { webWorkerRoots } from "./scripts/web-worker.ts";

const jsBanner = `/*
THIS IS A GENERATED/BUNDLED FILE BY VITE
*/`;

const workspaceRoot = await getWorkspaceRoot(import.meta.dirname);
const messagesDirectory = fileURLToPath(
  new URL(
    "./generated/",
    import.meta.resolve("@zotlit/plugin-messages/package.json"),
  ),
);
const publishedPlugin = PUBLISHED_PLUGINS.desktop;

export default defineConfig(({ mode }) => {
  const isProd = mode === "production";
  const isDev = mode === "development";
  const outDir = isProd ? "dist" : "dist-dev";
  const bundleDir = isProd ? BUNDLE_PACKAGE_DIR : outDir;
  const i18nDevServerPort = isDev
    ? parseI18nDevServerPort(process.env.I18N_DEV_SERVER)
    : undefined;

  const {
    resolve: resolveConfig,
    define,
    external,
    rendererPlugins,
  } = pluginBuildBase(mode, publishedPlugin.runtime);

  return {
    resolve: resolveConfig,
    define,
    build: {
      reportCompressedSize: false,
      lib: {
        entry: resolve(import.meta.dirname, "src/zt-main.ts"),
        formats: [isProd ? "es" : "cjs"],
        fileName: () => "main.js",
        cssFileName: "styles",
      },
      outDir: bundleDir,
      emptyOutDir: true,
      sourcemap: !isProd,
      minify: false,
      cssMinify: isProd,
      target: "es2025",
      copyPublicDir: false,
      rolldownOptions: {
        external,
        output: {
          postBanner: jsBanner,
          strictExecutionOrder: true,
          codeSplitting: false,
          sourcemapBaseUrl: isProd
            ? undefined
            : `${pathToFileURL(resolve(import.meta.dirname, outDir)).href}/`,
        },
      },
    },
    plugins: [
      nodeHttpModules(),
      obsidianI18n({
        project: join(workspaceRoot, "project.inlang"),
        output: messagesDirectory,
        excludeMessagePrefixes: EXCLUDE_MESSAGE_PREFIXES,
        includeMessages: INCLUDE_MESSAGES,
        targetLocaleMessagePrefixes: TARGET_LOCALE_MESSAGE_PREFIXES,
        servePacks:
          i18nDevServerPort === undefined
            ? undefined
            : { port: i18nDevServerPort },
      }),
      ...rendererPlugins,
      embeddedWorker({
        id: "virtual:zotero-reads-worker",
        entry: resolve(
          import.meta.dirname,
          "src/services/zotero-reads/worker.ts",
        ),
        runtime: RUNTIMES.desktopWorker,
        config: {
          mode,
          define,
          resolve: resolveConfig,
          plugins: [
            effectEntry("worker", { scopes: pluginCode }),
            effectEntryCheck("worker"),
            chineseSegmenterGlue(),
          ],
          minify: isProd,
          sourcemap: isProd ? false : "inline",
          target: "es2025",
        },
      }),
      ...webWorkerRoots(mode).map(embeddedWorker),
      embeddedWorker({
        id: "virtual:citation-parse-worker",
        entry: resolve(
          import.meta.dirname,
          "src/services/citation-parse/worker.ts",
        ),
        runtime: RUNTIMES.desktopWorker,
        config: {
          mode,
          define,
          resolve: resolveConfig,
          plugins: [
            effectEntry("worker", { scopes: pluginCode }),
            effectEntryCheck("worker"),
          ],
          minify: isProd,
          sourcemap: isProd ? false : "inline",
          target: "es2025",
        },
      }),
      obsidianBuildPlugin({
        packageRoot: import.meta.dirname,
        workspaceRoot,
        plugin: publishedPlugin,
        stageResources,
        isDev,
        isProd,
        outDir: resolve(import.meta.dirname, outDir),
        bundleDir: resolve(import.meta.dirname, bundleDir),
      }),
      Boolean(process.env.ANALYZE) &&
        unstableRolldownAdapter(
          analyzer({
            analyzerMode: process.env.ANALYZE === "json" ? "json" : "static",
            fileName: resolve(import.meta.dirname, "bundle-stats"),
            defaultSizes: "stat",
          }),
        ),
    ],
  };
});

async function stageResources(dir: string): Promise<void> {
  await mkdir(dir, { recursive: true });
  const contractDir = dirname(fullContractIRPath);
  const sources = [
    ...(await readdir(messagesDirectory))
      .filter((name) => name.endsWith(".json") && name !== "en.json")
      .map((name) => join(messagesDirectory, name)),
    ...(await readdir(contractDir))
      .filter((name) => name.endsWith(".schema.json"))
      .map((name) => join(contractDir, name)),
    join(workspaceRoot, "packages/item-query/generated/query.schema.json"),
  ];
  await Promise.all(
    sources.map((source) => cp(source, join(dir, basename(source)))),
  );
}

function parseI18nDevServerPort(value: string | undefined): number | undefined {
  if (!value || value === "false") return undefined;
  const port = Number(value);
  return Number.isInteger(port) && port > 0 ? port : 9092;
}
