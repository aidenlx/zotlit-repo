export default defineConfig(({ mode }) => {
  const isProd = mode === "production";
  const isDev = mode === "development";
  // A production build writes the bundle package, which the publish
  // repository builds main.js from, and then builds dist/main.js from that
  // package the same way. A development build writes main.js directly.
  const outDir = isProd ? "dist" : "dist-dev";
  const bundleDir = isProd ? BUNDLE_PACKAGE_DIR : outDir;
  const i18nDevServerPort = isDev
    ? parseI18nDevServerPort(process.env.I18N_DEV_SERVER)
    : undefined;

  const resolveConfig = {
    alias: {
      "@zotlit/db/contract/ir.runtime.json": fullContractIRPath,
      // The Node build of fflate loads `node:worker_threads` at import for its
      // asynchronous functions. The plugin calls the synchronous ones only.
      fflate: "fflate/browser",
    },
    conditions: ["module", "node", "development|production"],
    tsconfigPaths: true,
  };
  const define = {
    __DEV__: JSON.stringify(isDev),
    __PLUGIN_ID__: JSON.stringify(packageJson.obsidian.id),
    __ANNOTATION_SUGGESTER_ENABLED__: JSON.stringify(
      process.env.ANNOTATION_SUGGESTER_ENABLED === "true",
    ),
    __DOCS_SITE_URL__: JSON.stringify(
      parseDocsSiteUrl(process.env.DOCS_SITE_URL),
    ),
    __MIN_ELECTRON_VERSION__: JSON.stringify(
      parseMinElectronVersion(packageJson),
    ),
    __PANDOC_ENGINE__: JSON.stringify(pandocEngine),
    __CHINESE_SEGMENTER__: JSON.stringify(chineseSegmenter),
    "process.env.NODE_ENV": JSON.stringify(mode),
  };

  return {
    resolve: resolveConfig,
    define,
    build: {
      reportCompressedSize: false,
      lib: {
        entry: resolve(import.meta.dirname, "src/zt-main.ts"),
        // The bundle package is an ES module; the publish build makes it CommonJS.
        formats: [isProd ? "es" : "cjs"],
        fileName: () => "main.js",
        cssFileName: "styles",
      },
      outDir: bundleDir,
      emptyOutDir: true,
      // Obsidian's loader retains inline maps with the evaluated source text.
      sourcemap: !isProd,
      // The publish build minifies main.js; the stylesheet is final here.
      minify: false,
      cssMinify: isProd,
      target: "es2025",
      copyPublicDir: false,
      rolldownOptions: {
        external: HOST_MODULES,
        output: {
          postBanner: jsBanner,
          // Effect 4.1.0 under Rolldown 1.1 otherwise leaves modules reached through
          // `export * from "effect"` uninitialized, or drops them: the plugin then
          // fails at load. This runs every module in source order.
          strictExecutionOrder: true,
          codeSplitting: false,
          // plugin:zotlit is synthetic, so DevTools needs an absolute map URL.
          // build:dev is uncached because this URL belongs to this checkout.
          sourcemapBaseUrl: isProd
            ? undefined
            : `${pathToFileURL(resolve(import.meta.dirname, outDir)).href}/`,
        },
      },
    },
    plugins: [
      nodeHttpModules(),
      obsidianI18n({
        project: join(workspaceRoot, "project.inlang"),
        output: messagesDirectory,
        excludeMessagePrefixes: EXCLUDE_MESSAGE_PREFIXES,
        includeMessages: INCLUDE_MESSAGES,
        targetLocaleMessagePrefixes: TARGET_LOCALE_MESSAGE_PREFIXES,
        servePacks:
          i18nDevServerPort === undefined
            ? undefined
            : { port: i18nDevServerPort },
      }),
      effectEntry("renderer", { scopes: pluginCode }),
      effectEntryCheck("renderer"),
      preact(),
      tailwindcss(),
      pandocFilterVariants(),
      embeddedWorker({
        id: "virtual:zotero-reads-worker",
        entry: resolve(
          import.meta.dirname,
          "src/services/zotero-reads/worker.ts",
        ),
        config: {
          mode,
          define,
          resolve: resolveConfig,
          plugins: [
            effectEntry("worker", { scopes: pluginCode }),
            effectEntryCheck("worker"),
            // ZoteroReads holds the Item Lookup, which segments Chinese.
            chineseSegmenterGlue(),
          ],
          external: builtins,
          minify: isProd,
          sourcemap: isProd ? false : "inline",
          target: "es2025",
        },
      }),
      embeddedWorker({
        id: "virtual:citation-parse-worker",
        entry: resolve(
          import.meta.dirname,
          "src/services/citation-parse/worker.ts",
        ),
        config: {
          mode,
          define,
          resolve: resolveConfig,
          plugins: [
            effectEntry("worker", { scopes: pluginCode }),
            effectEntryCheck("worker"),
          ],
          external: builtins,
          minify: isProd,
          sourcemap: isProd ? false : "inline",
          target: "es2025",
        },
      }),
      obsidianBuildPlugin({
        packageRoot: import.meta.dirname,
        workspaceRoot,
        plugin: publishedPlugin,
        stageResources,
        isDev,
        isProd,
        outDir: resolve(import.meta.dirname, outDir),
        bundleDir: resolve(import.meta.dirname, bundleDir),
      }),
      Boolean(process.env.ANALYZE) &&
        unstableRolldownAdapter(
          analyzer({
            analyzerMode: process.env.ANALYZE === "json" ? "json" : "static",
            fileName: resolve(import.meta.dirname, "bundle-stats"),
            defaultSizes: "stat",
          }),
        ),
    ],
  };
});

/**
 * Everything the installed plugin downloads at runtime from the Resource
 * Release (ADR 0019): the Language Packs other than the bundled base locale,
 * the template data JSON Schemas, and the Item Query Schema.
 */
async function stageResources(dir: string): Promise<void> {
  await mkdir(dir, { recursive: true });
  const contractDir = dirname(fullContractIRPath);
  const sources = [
    ...(await readdir(messagesDirectory))
      .filter((name) => name.endsWith(".json") && name !== "en.json")
      .map((name) => join(messagesDirectory, name)),
    ...(await readdir(contractDir))
      .filter((name) => name.endsWith(".schema.json"))
      .map((name) => join(contractDir, name)),
    join(workspaceRoot, "packages/item-query/generated/query.schema.json"),
  ];
  await Promise.all(
    sources.map((source) => cp(source, join(dir, basename(source)))),
  );
}

/** Opt-in via I18N_DEV_SERVER=true (or a port number); defaults to 9092. */
/**
 * The docs origin baked into the build: Stable Docs unless CI names
 * Pre-release Docs for a pre-release line. An origin only, no trailing slash,
 * so link constants append their paths to it.
 */
function parseDocsSiteUrl(value: string | undefined): string {
  const fallback = "https://zotlit.aidenlx.site";
  if (!value) return fallback;
  const url = new URL(value);
  if (url.pathname !== "/" || url.search || url.hash) {
    throw new Error(
      `DOCS_SITE_URL must be an origin with no path, got ${JSON.stringify(value)}`,
    );
  }
  return url.origin;
}

function parseI18nDevServerPort(value: string | undefined): number | undefined {
  if (!value || value === "false") return undefined;
  const port = Number(value);
  return Number.isInteger(port) && port > 0 ? port : 9092;
}
