import preact from "@preact/preset-vite";
import tailwindcss from "@tailwindcss/vite";
import { cp, mkdir, readdir } from "node:fs/promises";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { defineConfig } from "vite";

import { obsidianI18n } from "@zotlit/obsidian-i18n/vite";
import { effectEntry, effectEntryCheck } from "@zotlit/plugin-kernel/vite";
import {
  INCLUDE_MESSAGE_PREFIXES,
  INCLUDE_MESSAGES,
  READER_MESSAGES_DIRECTORY,
  TARGET_LOCALE_MESSAGE_PREFIXES,
} from "@zotlit/reader-messages/language-pack-options";
import { getWorkspaceRoot } from "@zotlit/scripts/package-roots";
import { PLUGIN_KERNEL, pluginPackages } from "@zotlit/scripts/plugin-packages";
import { HOST_MODULES } from "@zotlit/scripts/shell/build";
import { obsidianBuildPlugin } from "@zotlit/scripts/shell/host-build";
import {
  BUNDLE_PACKAGE_DIR,
  PUBLISHED_PLUGINS,
} from "@zotlit/scripts/shell/plugins";

import { buildDefines } from "./build-defines.ts";

const jsBanner = `/*
THIS IS A GENERATED/BUNDLED FILE BY VITE
Contains PDF.js (pdf.js-zotlit fork), Copyright Mozilla Foundation, Apache-2.0. See NOTICE.
*/`;

const packageRoot = import.meta.dirname;
const workspaceRoot = await getWorkspaceRoot(packageRoot);
const pluginCode = [
  resolve(packageRoot, "src"),
  ...pluginPackages(packageRoot)
    .filter(({ name }) => name !== PLUGIN_KERNEL)
    .map(({ root }) => join(root, "src")),
];

export default defineConfig(({ mode }) => {
  const isProd = mode === "production";
  const isDev = mode === "development";
  const outDir = isProd ? "dist" : "dist-dev";
  const bundleDir = isProd ? BUNDLE_PACKAGE_DIR : outDir;

  return {
    resolve: {
      alias: { "@zotlit/plugin-messages": READER_MESSAGES_DIRECTORY },
      conditions: ["module", "browser", "development|production"],
    },
    define: {
      ...buildDefines(isDev),
      "process.env.NODE_ENV": JSON.stringify(mode),
    },
    build: {
      reportCompressedSize: false,
      lib: {
        entry: resolve(packageRoot, "src/main.ts"),
        formats: [isProd ? "es" : "cjs"],
        fileName: () => "main.js",
        cssFileName: "styles",
      },
      outDir: bundleDir,
      emptyOutDir: true,
      sourcemap: !isProd,
      minify: false,
      cssMinify: isProd,
      target: "es2025",
      copyPublicDir: false,
      rolldownOptions: {
        external: HOST_MODULES,
        onLog(level, log, handler) {
          if (log.code === "IMPORT_IS_UNDEFINED") throw new Error(log.message);
          handler(level, log);
        },
        output: {
          postBanner: jsBanner,
          strictExecutionOrder: true,
          codeSplitting: false,
          sourcemapBaseUrl: isProd
            ? undefined
            : `${pathToFileURL(resolve(packageRoot, outDir)).href}/`,
        },
      },
    },
    plugins: [
      obsidianI18n({
        project: join(workspaceRoot, "project.inlang"),
        output: READER_MESSAGES_DIRECTORY,
        includeMessagePrefixes: INCLUDE_MESSAGE_PREFIXES,
        includeMessages: INCLUDE_MESSAGES,
        targetLocaleMessagePrefixes: TARGET_LOCALE_MESSAGE_PREFIXES,
      }),
      effectEntry("renderer", { scopes: pluginCode }),
      effectEntryCheck("renderer"),
      preact(),
      tailwindcss(),
      obsidianBuildPlugin({
        packageRoot,
        workspaceRoot,
        plugin: PUBLISHED_PLUGINS.reader,
        stageResources,
        isDev,
        isProd,
        outDir: resolve(packageRoot, outDir),
        bundleDir: resolve(packageRoot, bundleDir),
      }),
    ],
  };
});

async function stageResources(dir: string): Promise<void> {
  await mkdir(dir, { recursive: true });
  const packs = (await readdir(READER_MESSAGES_DIRECTORY)).filter(
    (name) => name.endsWith(".json") && name !== "en.json",
  );
  await Promise.all(
    packs.map((name) =>
      cp(join(READER_MESSAGES_DIRECTORY, name), join(dir, name)),
    ),
  );
}
